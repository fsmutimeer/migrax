package org.migrax.helidon;

import io.helidon.microprofile.testing.junit5.AddConfig;
import io.helidon.microprofile.testing.junit5.HelidonTest;
import jakarta.inject.Inject;
import jakarta.inject.Named;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.ResultSet;
import javax.sql.DataSource;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;

/**
 * With migrax.migrate-at-startup=false a pipeline migrates: the application starts without
 * migrating, and readiness and the gauge report what waits.
 */
@HelidonTest
@AddConfig(key = "migrax.migrate-at-startup", value = "false")
// Migrax reports on the empty data source; Hibernate validates its own one at startup, which
// gets its table from the URL.
@AddConfig(key = "migrax.datasource", value = "other")
@AddConfig(key = "javax.sql.DataSource.notes.dataSource.url",
    value = "jdbc:h2:mem:notes_report_only;DB_CLOSE_DELAY=-1;INIT=CREATE TABLE IF NOT EXISTS "
        + "Memo (id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL, memoText varchar(255) "
        + "NOT NULL, CONSTRAINT Memo_pkey PRIMARY KEY (id))")
class MigraxReportOnlyTest {
  @Inject
  @Named("other")
  DataSource other;

  @Inject
  @org.eclipse.microprofile.health.Readiness
  MigraxReadinessCheck readiness;

  @Test
  void reportsWithoutMigrating() throws Exception {
    try (Connection connection = other.getConnection();
         ResultSet tables = connection.getMetaData().getTables(null, null, "MIGRAX_HISTORY",
             null)) {
      assertFalse(tables.next());
    }
    var response = readiness.call();
    assertEquals(org.eclipse.microprofile.health.HealthCheckResponse.Status.DOWN,
        response.getStatus(), String.valueOf(response.getData()));
    assertEquals(1L, response.getData().orElseThrow().get("pending"));
    assertEquals(1.0, org.migrax.helidon.app.Observability.REGISTRY
        .get("migrax.migrations.pending").gauge().value());
  }
}
