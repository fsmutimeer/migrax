package org.migrax.helidon;

import io.helidon.microprofile.testing.junit5.AddConfig;
import io.helidon.microprofile.testing.junit5.HelidonTest;
import jakarta.inject.Inject;
import jakarta.inject.Named;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.ResultSet;
import java.util.ArrayList;
import java.util.List;
import javax.sql.DataSource;

import static org.junit.jupiter.api.Assertions.assertEquals;

/**
 * A second database, the data source billing: migrated at startup from its own folder
 * (db/billing) with its own placeholders; readiness and the pending gauge report it. The default
 * database is a data source of this test's own, so the other tests' databases stay untouched.
 */
@HelidonTest
@AddConfig(key = "migrax.datasource", value = "main2")
@AddConfig(key = "javax.sql.DataSource.main2.dataSourceClassName",
    value = "org.h2.jdbcx.JdbcDataSource")
@AddConfig(key = "javax.sql.DataSource.main2.dataSource.url",
    value = "jdbc:h2:mem:helidon_two_main;DB_CLOSE_DELAY=-1")
@AddConfig(key = "javax.sql.DataSource.main2.dataSource.user", value = "sa")
@AddConfig(key = "javax.sql.DataSource.billing.dataSourceClassName",
    value = "org.h2.jdbcx.JdbcDataSource")
@AddConfig(key = "javax.sql.DataSource.billing.dataSource.url",
    value = "jdbc:h2:mem:helidon_two_billing;DB_CLOSE_DELAY=-1")
@AddConfig(key = "javax.sql.DataSource.billing.dataSource.user", value = "sa")
@AddConfig(key = "migrax.databases.billing.placeholders.owner", value = "billing_team")
// Hibernate validates its own data source at startup; it gets its table from the URL.
@AddConfig(key = "javax.sql.DataSource.notes.dataSource.url",
    value = "jdbc:h2:mem:notes_two_databases;DB_CLOSE_DELAY=-1;INIT=CREATE TABLE IF NOT EXISTS "
        + "Memo (id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL, memoText varchar(255) "
        + "NOT NULL, CONSTRAINT Memo_pkey PRIMARY KEY (id))")
class MigraxDatabasesTest {
  @Inject
  @Named("main2")
  DataSource main;

  @Inject
  @Named("billing")
  DataSource billing;

  @Inject
  @org.eclipse.microprofile.health.Readiness
  MigraxReadinessCheck readiness;

  /** The tracing test of the other class counts spans in the same exporter. */
  @AfterAll
  static void forgetSpans() {
    org.migrax.helidon.app.Observability.SPANS.reset();
  }

  @Test
  void migratesEveryConfiguredDatabase() throws Exception {
    assertEquals(List.of("0001_memos.sql"), strings(main, "SELECT version FROM migrax_history"));
    assertEquals(List.of("0001_invoices.sql"),
        strings(billing, "SELECT version FROM migrax_history"));
    assertEquals(List.of("billing_team"), strings(billing, "SELECT owner FROM invoice"));
  }

  @Test
  void readinessAndTheGaugeReportEachDatabase() {
    var response = readiness.call();
    assertEquals(org.eclipse.microprofile.health.HealthCheckResponse.Status.UP,
        response.getStatus(), String.valueOf(response.getData()));
    var data = response.getData().orElseThrow();
    assertEquals(1L, data.get("applied"));
    assertEquals(1L, data.get("billing.applied"));
    assertEquals(0L, data.get("billing.pending"));
    assertEquals(0.0, org.migrax.helidon.app.Observability.REGISTRY
        .get("migrax.migrations.pending").tag("database", "billing").gauge().value());
  }

  private static List<String> strings(DataSource dataSource, String sql) throws Exception {
    List<String> values = new ArrayList<>();
    try (Connection connection = dataSource.getConnection();
         var statement = connection.createStatement();
         ResultSet rows = statement.executeQuery(sql)) {
      while (rows.next()) {
        values.add(rows.getString(1));
      }
    }
    return values;
  }
}
