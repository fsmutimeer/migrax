package org.migrax;

import org.migrax.dialect.Dialects;
import org.migrax.model.ModelExtractor;
import org.migrax.model.NamingStrategy;
import org.migrax.model.SchemaModel;
import org.migrax.ops.CreateTable;
import org.junit.jupiter.api.Test;

import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** Spring Data JDBC's own mapping of the test aggregates, read without a database. */
class SpringDataJdbcReaderTest {
  private static ModelExtractor.Result read(String dialect, ModelExtractor.Mode mode)
      throws Exception {
    return ModelExtractor.extract(Thread.currentThread().getContextClassLoader(),
        "org.migrax.springdata.fixtures", NamingStrategy.SPRING, Dialects.byName(dialect),
        Map.of(), mode);
  }

  @Test
  void readsAggregatesWithTheirChildTables() throws Exception {
    // No JPA entities in the package: found without --extractor.
    ModelExtractor.Result result = read("postgresql", ModelExtractor.Mode.AUTO);
    assertTrue(result.source().startsWith("Spring Data JDBC"), result.source());
    SchemaModel model = result.model();
    assertEquals(List.of("customers", "hobby", "note", "note_line", "order", "product", "profile",
        "region", "tag"),
        model.tables().stream().map(SchemaModel.Table::name).toList());

    SchemaModel.Table customers = model.table("customers");
    assertTrue(customers.column("id").identity(), "a Long id is generated by the database");
    assertEquals("varchar", customers.column("status").logicalType(), "enums by name");
    assertEquals("bytea", customers.column("photo").sqlType());
    assertNotNull(customers.column("home_street"), "embedded with its prefix");
    assertNotNull(customers.column("\"Nick\""), "mixed case keeps its case");
    assertNull(customers.column("scratch"), "@Transient");
    assertEquals("bigint", customers.column("region").logicalType(), "the other root's id");
    assertTrue(customers.foreignKeys().isEmpty(), "no foreign key to another aggregate");

    // A list: back-reference and index columns, named by @MappedCollection.
    SchemaModel.Table order = model.table("order");
    assertEquals(List.of("customer_id", "position", "id", "product"),
        order.columns().stream().map(SchemaModel.Column::name).toList());
    assertEquals(List.of("id"), order.primaryKey().columns());
    assertEquals(new SchemaModel.ForeignKey("fk_order_customers", List.of("customer_id"),
        "customers", List.of("id")), order.foreignKeys().get(0));
    // A map entry is its parent and its key; a set element has no key.
    assertEquals(List.of("customers", "customers_key"),
        model.table("note").primaryKey().columns());
    assertNull(model.table("tag").primaryKey());
    assertEquals(List.of("customers"), model.table("profile").primaryKey().columns());
    // A list inside a map value without an id: its rows also carry the map key.
    SchemaModel.Table noteLine = model.table("note_line");
    assertEquals(List.of("customers", "customers_key", "note_key", "words"),
        noteLine.columns().stream().map(SchemaModel.Column::name).toList());
    assertEquals(List.of("customers", "customers_key", "note_key"),
        noteLine.primaryKey().columns());
    assertEquals("customers", noteLine.foreignKeys().get(0).referencedTable());
    // @Table on a child entity doesn't make it a root: its set still points at the customer.
    assertEquals(List.of("customers"), model.table("hobby").foreignKeys().get(0).columns());

    assertFalse(model.table("region").column("id").identity());
    assertEquals(new SchemaModel.Sequence("region_seq", 1L, 1L), model.sequence("region_seq"));
    assertFalse(model.table("product").column("sku").identity(), "String ids come from the app");
  }

  @Test
  void keepsTheCaseOfWrittenNamesWhereTheDatabaseFoldsToUpperCase() throws Exception {
    // Spring Data JDBC quotes every name: on H2 a written lower-case name is case-sensitive,
    // a derived name is upper case.
    SchemaModel model = read("h2", ModelExtractor.Mode.SPRING_DATA_JDBC).model();
    SchemaModel.Table customers = model.table("\"customers\"");
    assertNotNull(customers, model.tables().toString());
    assertNotNull(customers.column("\"mail\""));
    assertNotNull(customers.column("name"));
    assertNotNull(model.table("\"ORDER\""), "a reserved word in Spring's case");
    String sql = Dialects.byName("h2").render(new CreateTable(customers));
    assertTrue(sql.startsWith("CREATE TABLE \"customers\" (id bigint GENERATED BY DEFAULT AS "
        + "IDENTITY NOT NULL, name varchar(255), \"mail\" varchar(255)"), sql);
    assertEquals("customers_pkey", SchemaModel.primaryKeyConstraintName(customers.name()));
  }
}
