package org.migrax.api;

import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.net.URL;
import java.net.URLClassLoader;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** The Java API, end to end on H2. */
class MigraxTest {
  private static final String BOOK = "CREATE TABLE book (id BIGINT GENERATED BY DEFAULT AS "
      + "IDENTITY PRIMARY KEY, title VARCHAR(100) NOT NULL);\n";

  @TempDir
  Path project;

  private JdbcDataSource database(String name) {
    JdbcDataSource dataSource = new JdbcDataSource();
    dataSource.setURL("jdbc:h2:mem:api_" + name + ";DB_CLOSE_DELAY=-1");
    return dataSource;
  }

  private Path migrations() throws Exception {
    return Files.createDirectories(project.resolve("src/main/resources/db/migration"));
  }

  private Migrax.Builder configure(JdbcDataSource dataSource) throws Exception {
    return Migrax.configure().dataSource(dataSource).projectDirectory(project)
        .locations("filesystem:" + migrations()).entities("org.migrax.api.fixture");
  }

  @Test
  void migratesReportsStatusAndValidatesTheEntities() throws Exception {
    Files.writeString(migrations().resolve("0001_book.sql"), BOOK);
    Files.writeString(migrations().resolve("0002_note.sql"), "CREATE TABLE note (id INT);\n");
    Migrax migrax = configure(database("migrate")).load();

    Migrax.Status before = migrax.status();
    assertEquals(0, before.applied());
    assertEquals(2, before.pending());
    assertFalse(before.upToDate());

    Migrax.MigrateResult result = migrax.migrate();
    assertEquals(2, result.applied());
    assertEquals(List.of(new Migrax.SchemaResult(null, 2)), result.schemas());
    assertTrue(migrax.status().upToDate());
    assertEquals(Migrax.State.APPLIED, migrax.status().migrations().get(0).state());
    assertEquals(0, migrax.migrate().applied());

    Migrax.Validation validation = migrax.validate();
    assertTrue(validation.valid(), validation.problems().toString());
    assertTrue(validation.entities().startsWith("Hibernate "), validation.entities());
  }

  @Test
  void validationNamesWhatTheMigrationsMiss() throws Exception {
    Files.writeString(migrations().resolve("0001_book.sql"),
        "CREATE TABLE book (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);\n");
    Migrax migrax = configure(database("missing")).load();
    migrax.migrate();
    Migrax.Validation validation = migrax.validate();
    assertFalse(validation.valid());
    assertTrue(validation.problems().toString().contains("title"),
        validation.problems().toString());
  }

  @Test
  void anUnmappedColumnCountsOnlyWhenInsertsCantLeaveItOut() throws Exception {
    Files.writeString(migrations().resolve("0001_book.sql"), BOOK);
    Files.writeString(migrations().resolve("0002_note.sql"),
        "ALTER TABLE book ADD COLUMN note VARCHAR(20);\n");
    Migrax migrax = configure(database("extra_column")).load();
    migrax.migrate();
    assertTrue(migrax.validate().valid(), migrax.validate().problems().toString());

    Files.writeString(migrations().resolve("0003_isbn.sql"),
        "ALTER TABLE book ADD COLUMN isbn VARCHAR(13) NOT NULL;\n");
    migrax = configure(database("extra_column")).load();
    migrax.migrate();
    Migrax.Validation validation = migrax.validate();
    assertEquals(1, validation.problems().size(), validation.problems().toString());
    assertTrue(validation.problems().get(0).contains("isbn"), validation.problems().toString());
  }

  @Test
  void rollsBackAndTestsTheRollbackScripts() throws Exception {
    Path rollback = Files.createDirectories(migrations().resolve("rollback"));
    Files.writeString(migrations().resolve("0001_book.sql"), BOOK);
    Files.writeString(rollback.resolve("0001_book.sql"), "DROP TABLE book;\n");
    Files.writeString(migrations().resolve("0002_index.sql"),
        "CREATE INDEX idx_title ON book (title);\n");
    Files.writeString(rollback.resolve("0002_index.sql"), "DROP INDEX idx_title;\n");
    JdbcDataSource dataSource = database("rollback");
    Migrax migrax = configure(dataSource).load();
    migrax.migrate();

    Migrax.RollbackTest test = migrax.testRollbacks();
    assertTrue(test.ok(), test.summary());
    assertEquals("ok (2 rolled back and re-applied)", test.summary());
    assertTrue(migrax.status().upToDate());

    assertEquals(List.of("0002_index.sql"), migrax.rollback(1));
    assertEquals(1, migrax.status().pending());
    migrax.migrate();
    assertEquals(List.of("0002_index.sql", "0001_book.sql"), migrax.rollback(2));
    assertEquals(0, migrax.status().applied());
  }

  @Test
  void aBrokenRollbackScriptIsNamed() throws Exception {
    Path rollback = Files.createDirectories(migrations().resolve("rollback"));
    Files.writeString(migrations().resolve("0001_book.sql"), BOOK);
    Files.writeString(rollback.resolve("0001_book.sql"), "DROP TABLE book;\n");
    Files.writeString(migrations().resolve("0002_index.sql"),
        "CREATE INDEX idx_title ON book (title);\n");
    // Leaves the index behind: applying 0002 again fails.
    Files.writeString(rollback.resolve("0002_index.sql"), "SELECT 1;\n");
    Migrax migrax = configure(database("broken")).load();
    migrax.migrate();
    Migrax.RollbackTest test = migrax.testRollbacks();
    assertFalse(test.ok());
    assertTrue(test.summary().contains("0002_index.sql"), test.summary());
  }

  @Test
  void rollbackToKeepsTheNamedMigration() throws Exception {
    Path rollback = Files.createDirectories(migrations().resolve("rollback"));
    for (String table : List.of("a", "b", "c")) {
      String name = "000" + (table.charAt(0) - 'a' + 1) + "_" + table + ".sql";
      Files.writeString(migrations().resolve(name), "CREATE TABLE " + table + " (id INT);\n");
      Files.writeString(rollback.resolve(name), "DROP TABLE " + table + ";\n");
    }
    Migrax migrax = configure(database("rollback_to")).load();
    migrax.migrate();
    assertEquals(List.of("0003_c.sql", "0002_b.sql"), migrax.rollbackTo("0001"));
    assertEquals(1, migrax.status().applied());
    IllegalStateException unknown = assertThrows(IllegalStateException.class,
        () -> migrax.rollbackTo("0009"));
    assertTrue(unknown.getMessage().contains("0009"), unknown.getMessage());
  }

  @Test
  void aMissingRollbackScriptStopsBeforeAnythingIsRolledBack() throws Exception {
    Files.writeString(migrations().resolve("0001_book.sql"), BOOK);
    Migrax migrax = configure(database("no_script")).load();
    migrax.migrate();
    IllegalStateException error = assertThrows(IllegalStateException.class,
        () -> migrax.rollback(1));
    assertTrue(error.getMessage().contains("No rollback script for 0001_book.sql"),
        error.getMessage());
    assertEquals(1, migrax.status().applied());
  }

  @Test
  void readsClasspathLocationsWithTheirRollbackScriptsAndJavaMigrations() throws Exception {
    Path classes = project.resolve("classes");
    Path folder = Files.createDirectories(classes.resolve("db/tenant"));
    Files.writeString(folder.resolve("0001_note.sql"), "CREATE TABLE note (id INT);\n");
    Files.createDirectories(folder.resolve("rollback"));
    Files.writeString(folder.resolve("rollback/0001_note.sql"), "DROP TABLE note;\n");
    JdbcDataSource dataSource = database("classpath");
    JavaMigration seed = new JavaMigration() {
      @Override
      public void migrate(Connection connection) throws Exception {
        connection.createStatement().executeUpdate("INSERT INTO note VALUES (1)");
      }

      @Override
      public void rollback(Connection connection) throws Exception {
        connection.createStatement().executeUpdate("DELETE FROM note");
      }

      @Override
      public String version() {
        return "V0002__Seed";
      }
    };
    try (URLClassLoader loader = new URLClassLoader(new URL[] {classes.toUri().toURL()},
        getClass().getClassLoader())) {
      Migrax migrax = Migrax.configure().dataSource(dataSource).classLoader(loader)
          .settings(Map.of("migrax.locations", "classpath:db/tenant/")).javaPackage(null)
          .javaMigrations(seed).load();
      assertEquals(2, migrax.migrate().applied());
      assertEquals(List.of("V0002__Seed", "0001_note.sql"), migrax.rollback(2));
      assertEquals(0, migrax.status().applied());
    }
  }

  @Test
  void migratesEverySchema() throws Exception {
    JdbcDataSource dataSource = database("schemas");
    try (Connection connection = dataSource.getConnection()) {
      connection.createStatement().execute("CREATE SCHEMA tenant_a");
      connection.createStatement().execute("CREATE SCHEMA tenant_b");
    }
    Files.writeString(migrations().resolve("0001_book.sql"), BOOK);
    Migrax migrax = configure(dataSource).schemas("TENANT_A", "TENANT_B").load();
    Migrax.MigrateResult result = migrax.migrate();
    assertEquals(2, result.applied());
    assertEquals(List.of(new Migrax.SchemaResult("TENANT_A", 1),
        new Migrax.SchemaResult("TENANT_B", 1)), result.schemas());
    assertEquals(2, migrax.status().applied());
    assertTrue(migrax.validate().valid(), migrax.validate().problems().toString());
  }

  @Test
  void needsADatabaseAndUniqueFileNames() throws Exception {
    assertThrows(IllegalStateException.class, () -> Migrax.configure().load());
    Path other = Files.createDirectories(project.resolve("other"));
    Files.writeString(migrations().resolve("0001_book.sql"), BOOK);
    Files.writeString(other.resolve("0001_book.sql"), BOOK);
    IllegalStateException twice = assertThrows(IllegalStateException.class,
        () -> Migrax.configure().dataSource(database("twice"))
            .locations("filesystem:" + migrations(), "filesystem:" + other).load());
    assertTrue(twice.getMessage().contains("0001_book.sql"), twice.getMessage());
  }

  @Test
  void connectsWithAUrl() throws Exception {
    Files.writeString(migrations().resolve("0001_book.sql"), BOOK);
    Migrax migrax = Migrax.configure().url("jdbc:h2:mem:api_url;DB_CLOSE_DELAY=-1", "sa", "")
        .locations("filesystem:" + migrations()).load();
    assertEquals(1, migrax.migrate().applied());
  }
}
