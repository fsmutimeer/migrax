package org.migrax.cli;

import org.migrax.dialect.Dialect;
import org.migrax.diff.DatabaseBaseline;
import org.migrax.diff.DiffEngine;
import org.migrax.diff.Renames;
import org.migrax.model.SchemaModel;
import org.migrax.ops.Operation;
import org.migrax.plugin.DatabaseSchemaReader;
import org.migrax.runner.SqlScript;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * {@code migrax.schema-file} on a real database. A schema with an identity column, unnamed
 * constraints, a text and a CURRENT_TIMESTAMP default and a named index is read: everything in
 * it must be in the model, and reading it again on emptied tables must give the same model
 * (names the database makes up are replaced). The migration generated from it must build
 * exactly that schema, and a first generate against a database that already has the tables
 * must find nothing to change. Works
 * on its own sf_ tables only, so what other tests left in the database stays. Shared by the H2
 * unit test and the integration test on every database.
 */
public final class SchemaFileScenario {
  private SchemaFileScenario() {}

  /** The schema file, with the types and identity syntax each engine accepts. */
  static String schema(Dialect dialect) {
    String id = dialect.id().equals("oracle") ? "NUMBER(19)" : "BIGINT";
    String text = dialect.id().equals("oracle") ? "VARCHAR2" : "VARCHAR";
    // SQL Server's TIMESTAMP is a row version, not a point in time.
    String time = dialect.id().equals("sqlserver") ? "DATETIME2" : "TIMESTAMP";
    // MySQL's own types, which must keep their fraction digits.
    String mysqlOnly = mysql(dialect) ? ", paid_at DATETIME(6)" : "";
    String identity = switch (dialect.id()) {
      case "mysql", "mariadb", "tidb" -> "BIGINT AUTO_INCREMENT NOT NULL PRIMARY KEY";
      case "sqlserver" -> "BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY";
      case "sqlite" -> "INTEGER PRIMARY KEY AUTOINCREMENT";
      default -> id + " GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY";
    };
    return """
        CREATE TABLE sf_customer (
          id %3$s,
          email %2$s(150) NOT NULL UNIQUE,
          status %2$s(10) DEFAULT 'new' NOT NULL,
          created_at %4$s DEFAULT CURRENT_TIMESTAMP NOT NULL
        );
        CREATE TABLE sf_order (
          id %1$s NOT NULL PRIMARY KEY,
          customer_id %1$s NOT NULL,
          total DECIMAL(12, 2) NOT NULL,
          CHECK (total >= 0),
          FOREIGN KEY (customer_id) REFERENCES sf_customer (id)%5$s
        );
        CREATE INDEX sf_order_total ON sf_order (total);
        """.formatted(id, text, identity, time, mysqlOnly);
  }

  public static void run(Connection connection, Dialect dialect) throws Exception {
    String sql = schema(dialect);
    SchemaModel first = read(connection, dialect, sql);
    assertComplete(first, dialect);
    assertEquals(first, read(connection, dialect, sql), dialect.id() + ": read twice");

    // The migration generate writes builds exactly the schema the file describes.
    dropOwnTables(connection);
    List<Operation> operations = new DiffEngine().diff(SchemaModel.empty(), first);
    String migration = MigrationSql.render(dialect, operations, null, SchemaModel.empty(),
        first);
    try {
      execute(connection, dialect, migration);
    } catch (Exception e) {
      throw new AssertionError(dialect.id() + ": the generated migration failed:\n" + migration,
          e);
    }
    SchemaModel built = own(DatabaseSchemaReader.read(connection, null, true));
    assertEquals(List.of(), new DiffEngine().diff(built, first).stream().map(dialect::render)
        .toList(), dialect.id() + ": after the generated migration\n" + migration);

    // The first generate against a database that already has the tables (created from the
    // file itself, with the names the database made up) finds nothing to change.
    dropOwnTables(connection);
    execute(connection, dialect, sql);
    SchemaModel existing = own(DatabaseBaseline.read(connection, null, first, true));
    SchemaModel desired = SchemaFile.withNamesFrom(
        DatabaseBaseline.align(first, existing, dialect), existing);
    assertEquals(List.of(), Renames.diff(existing, desired, List.of(), List.of()).stream()
        .map(dialect::render).toList(), dialect.id() + ": first generate on existing tables");
    dropOwnTables(connection);
  }

  /** Everything the file declares is in the model: comparing models with each other can't tell. */
  private static void assertComplete(SchemaModel model, Dialect dialect) {
    String engine = dialect.id() + ": ";
    SchemaModel.Table customer = model.table("sf_customer");
    SchemaModel.Table order = model.table("sf_order");
    assertTrue(customer != null && order != null, engine + "both tables: " + model);
    assertEquals(List.of("id"), customer.primaryKey().columns(), engine + customer);
    assertEquals(List.of("id"), order.primaryKey().columns(), engine + order);
    assertTrue(customer.column("id").identity(), engine + "identity: " + customer);
    assertTrue(customer.column("email").unique() || customer.indexes().stream()
        .anyMatch(i -> i.unique() && i.columns().equals(List.of("email"))),
        engine + "unique email: " + customer);
    assertEquals("'new'", customer.column("status").defaultValue(), engine + customer);
    assertTrue(customer.column("created_at").defaultValue() != null, engine + customer);
    if (mysql(dialect)) {
      assertEquals("datetime(6)", order.column("paid_at").sqlType(), engine + order);
    }
    assertEquals(1, order.foreignKeys().size(), engine + order);
    SchemaModel.ForeignKey key = order.foreignKeys().get(0);
    assertEquals(List.of("customer_id"), key.columns(), engine + key);
    assertEquals("sf_customer", key.referencedTable(), engine + key);
    assertEquals(List.of("id"), key.referencedColumns(), engine + key);
    assertEquals(1, order.checks().size(), engine + "the check: " + order);
    assertTrue(order.indexes().stream().anyMatch(i -> i.name().equals("sf_order_total")
        && i.columns().equals(List.of("total"))), engine + "the index: " + order);
  }

  /** What SchemaFile reads from an empty database the file was applied to. */
  private static SchemaModel read(Connection connection, Dialect dialect, String sql)
      throws Exception {
    dropOwnTables(connection);
    execute(connection, dialect, sql);
    return own(SchemaFile.withOwnNames(DatabaseSchemaReader.read(connection, null, true)));
  }

  private static void execute(Connection connection, Dialect dialect, String sql)
      throws Exception {
    connection.setAutoCommit(true);
    for (String statement : SqlScript.split(sql, mysql(dialect))) {
      try (Statement jdbc = connection.createStatement()) {
        jdbc.execute(statement);
      }
    }
  }

  private static boolean mysql(Dialect dialect) {
    return List.of("mysql", "mariadb", "tidb").contains(dialect.id());
  }

  /** The scenario's tables only. */
  private static SchemaModel own(SchemaModel model) {
    return new SchemaModel(model.tables().stream().filter(t -> t.name().startsWith("sf_"))
        .toList(), List.of());
  }

  private static void dropOwnTables(Connection connection) throws Exception {
    connection.setAutoCommit(true);
    for (String table : List.of("sf_order", "sf_customer")) {
      try (Statement jdbc = connection.createStatement()) {
        jdbc.execute("DROP TABLE " + table);
      } catch (SQLException absent) {
        // Not there yet.
      }
    }
  }
}
