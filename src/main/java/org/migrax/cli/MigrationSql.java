package org.migrax.cli;

import org.migrax.dialect.Dialect;
import org.migrax.diff.Migrations;
import org.migrax.model.SchemaModel;
import org.migrax.ops.AddColumn;
import org.migrax.ops.AlterColumn;
import org.migrax.ops.CreateTable;
import org.migrax.ops.DropColumn;
import org.migrax.ops.DropTable;
import org.migrax.ops.Operation;
import org.migrax.runner.MigrationLoader;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

/** Writes operations as migration SQL and rollback scripts. */
final class MigrationSql {
  private MigrationSql() {}

  /**
   * A migration file's SQL for the changes from {@code before} to {@code after}, prepared for
   * the database first ({@link Dialect#prepare}: SQLite rebuilds tables).
   */
  static String render(Dialect dialect, List<Operation> operations, String header,
                       SchemaModel before, SchemaModel after) {
    return render(dialect, dialect.prepare(operations, before, after), header);
  }

  /** A migration file's SQL: the "Generated by" line, an optional header, the statements. */
  static String render(Dialect dialect, List<Operation> operations, String header) {
    StringBuilder sql = new StringBuilder("-- Generated by Migrax ").append(Version.current())
        .append(" for ").append(dialect.id()).append("\n");
    if (header != null) {
      sql.append(header);
    }
    sql.append("\n");
    for (Operation operation : operations) {
      sql.append(dialect.render(operation)).append(";\n");
    }
    return sql.toString();
  }

  /** Writes rollback/<fileName>, with warnings about data the rollback cannot restore. */
  static void writeRollback(Path migrations, String fileName, Dialect dialect,
                            List<Operation> reverse, List<Operation> forward,
                            SchemaModel before, SchemaModel after)
      throws Exception {
    String header = rollbackHeader(fileName, forward, List.of(), List.of());
    String sql = reverse.isEmpty()
        ? "-- Generated by Migrax " + Version.current() + " for " + dialect.id() + "\n" + header
            + "-- Nothing to undo.\n"
        : render(dialect, reverse, header, before, after);
    write(migrations, fileName, sql);
  }

  /**
   * Writes rollback/<fileName> for a {@code --keep-data} migration: the structure, the kept
   * values, NOT NULL again and the column backups dropped, each phase prepared on its own.
   */
  static void writeRollback(Path migrations, String fileName, Dialect dialect,
                            KeepData.Plan plan, List<Operation> forward, SchemaModel before,
                            SchemaModel after)
      throws Exception {
    String header = rollbackHeader(fileName, forward, plan.kept(), plan.notes());
    if ("cockroachdb".equals(dialect.id()) && !plan.restores().isEmpty()) {
      header += "-- CockroachDB can't fill a column in the transaction that added it, so each "
          + "statement\n-- commits on its own:\n-- migrax:no-transaction\n";
    }
    StringBuilder sql = new StringBuilder(render(dialect, plan.reverse(), header, before,
        plan.middle()));
    plan.restores().forEach(statement -> sql.append(statement).append(";\n"));
    for (Operation operation : dialect.prepare(plan.finish(), plan.middle(), after)) {
      sql.append(dialect.render(operation)).append(";\n");
    }
    plan.cleanup().forEach(statement -> sql.append(statement).append(";\n"));
    write(migrations, fileName, sql.toString());
  }

  private static void write(Path migrations, String fileName, String sql) throws Exception {
    Path folder = migrations.resolve(MigrationLoader.ROLLBACK_FOLDER);
    Files.createDirectories(folder);
    Files.writeString(folder.resolve(fileName), sql);
  }

  /**
   * The rollback script's header: what it can't restore, and for {@code --keep-data} what it
   * restores ({@code notes}) instead of a warning for the {@code kept} changes.
   */
  private static String rollbackHeader(String fileName, List<Operation> forward,
                                       List<Operation> kept, List<String> notes) {
    StringBuilder header = new StringBuilder("-- Rollback for ").append(fileName)
        .append(". 'migrax rollback' runs it.\n");
    notes.forEach(note -> header.append("-- ").append(note).append('\n'));
    for (Operation operation : forward) {
      if (kept.contains(operation)) {
        continue;
      }
      String subject = Migrations.summary(operation).replaceFirst("^\\S+ \\S+ ", "");
      if (operation instanceof DropColumn || operation instanceof DropTable
          || operation instanceof AlterColumn alter && alter.destructive()) {
        header.append("-- WARNING: restores the structure of ").append(subject)
            .append(" but not its data.\n");
      } else if (operation instanceof AddColumn || operation instanceof CreateTable) {
        header.append("-- Note: deletes data written to ").append(subject)
            .append(" since the migration ran.\n");
      }
    }
    return header.toString();
  }
}
